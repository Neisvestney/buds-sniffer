    fun encrypt(plaintext: ByteArray): ByteArray {
        require(plaintext.size == BLOCK_SIZE) { "expected $BLOCK_SIZE bytes, got ${plaintext.size}" }
        return e1test(MAGIC, plaintext.toUnsigned(), STATIC_KEY).toBytes()
    }

    private fun e1test(key6: IntArray, input: IntArray, seed: IntArray): IntArray {
        val output = input.copyOf()
        blockCipher(output, keySchedule(seed), mode = 0)
        for (i in 0 until 16) output[i] = (key6[i % 6] + (output[i] xor input[i])) and 0xFF

        // negative entries are subtracted, positive ones xored
        val obf = IntArray(16) { i ->
            val c = SEED_OBFUSCATION[i]
            if (c < 0) (seed[i] + c) and 0xFF else seed[i] xor c
        }
        blockCipher(output, keySchedule(obf), mode = 1)
        return output
    }

    private fun keySchedule(seed: IntArray): IntArray {
        val out = IntArray(272)
        seed.copyInto(out, 0, 0, 16)
        val buf = IntArray(17)
        seed.copyInto(buf, 0, 0, 16)
        buf[16] = seed.take(16).fold(0) { acc, b -> acc xor b }

        for (rnd in 0 until 16) {
            for (i in 0 until 17) {
                val b = buf[i]
                buf[i] = ((b shl 3) or (b ushr 5)) and 0xFF
            }
            var readPos = (rnd + 1) % 17
            for (j in 0 until 16) {
                out[16 + rnd * 16 + j] = (KS_TABLE[0xF + rnd * 16 - j] + buf[readPos]) and 0xFF
                readPos++
                if (readPos > 16) readPos = 0
            }
        }
        return out
    }

    private fun blockCipher(state: IntArray, ek: IntArray, mode: Int) {
        val initial = state.copyOf()
        var s = state.copyOf()

        condMix(s, ek, 0, phase = 3)
        sboxSub(s)
        condMix(s, ek, 16, phase = 5)

        for (round in 1..8) {
            s = fibonacciMix(s)
            if (round == 8) {
                condMix(s, ek, 0x100, phase = 3)
                break
            }
            if (mode != 0 && round == 2) {
                for (i in 0 until 16) {
                    s[i] = if ((1 shl i) and MASK != 0) s[i] xor initial[i] else (initial[i] + s[i]) and 0xFF
                }
            }
            val off = round * 0x20
            condMix(s, ek, off, phase = 3)
            sboxSub(s)
            condMix(s, ek, off + 16, phase = 5)
        }
        s.copyInto(state)
    }

    // phase 3: bit set -> xor, clear -> add; phase 5: the other way round
    private fun condMix(s: IntArray, ek: IntArray, offset: Int, phase: Int) {
        for (i in 0 until 16) {
            val bitSet = (1 shl i) and MASK != 0
            val xor = if (phase == 3) bitSet else !bitSet
            val k = ek[offset + i]
            s[i] = if (xor) s[i] xor k else (k + s[i]) and 0xFF
        }
    }

    private fun sboxSub(s: IntArray) {
        for (pos in intArrayOf(0, 3, 4, 7, 8, 11, 12, 15)) s[pos] = SBOX[s[pos]]
        for (pos in intArrayOf(1, 2, 5, 6, 9, 10, 13, 14)) s[pos] = ISBOX[s[pos]]
    }

